APPROVED_ASSETS = Path(__file__).resolve().parents[1] / "fixtures" / "approved-assets"
REQUESTS_ROOT = Path(__file__).resolve().parents[1] / "fixtures" / "requests"

# PyYAML (YAML 1.1) loads these keys as int, bool, and None respectively.
NON_STRING_YAML_KEYS = (("1", "1"), ("on", "True"), ("null", "None"))


def test_missing_required_fields_fail_before_rendering():
    payload = """
identity:
  full_name: "Ada Lovelace"
  role: "Engineer"
template:
  id: business-card
"""

    result = load_and_validate_request(
        payload,
        source_name="invalid.yaml",
        approved_asset_roots=(APPROVED_ASSETS,),
    )

    assert result.outcome == ValidationOutcome.REJECTED
    assert result.request is None
    assert len(result.issues) == 1
    assert result.issues[0].code == ValidationCode.MISSING_REQUIRED
    assert result.issues[0].field == "identity.email"


def test_unknown_fields_are_rejected_deterministically():
    payload = """
identity:
  full_name: "Ada Lovelace"
  role: "Engineer"
  email: "ada@example.com"
  nickname: "Enchantress of Numbers"
template:
  id: business-card
  options:
    unsupported: true
metadata: "unexpected"
"""

    result = load_and_validate_request(
        payload,
        source_name="invalid.yaml",
        approved_asset_roots=(APPROVED_ASSETS,),
    )

    assert result.outcome == ValidationOutcome.REJECTED
    assert [issue.code for issue in result.issues] == [
        ValidationCode.UNKNOWN_FIELD,
        ValidationCode.UNKNOWN_FIELD,
        ValidationCode.UNKNOWN_FIELD,
    ]
    assert [issue.field for issue in result.issues] == [
        "identity.nickname",
        "metadata",
        "template.options.unsupported",
    ]


